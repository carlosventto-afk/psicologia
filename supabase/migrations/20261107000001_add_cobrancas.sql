-- Cobranca: agrupa sessoes de um mesmo paciente com valor fechado e tipo de
-- documento (nenhum/recibo/nota_fiscal), para ser recebida de uma vez.
-- "Cobrada" e derivado (vinculo ativo com cobranca aberta), nao um novo
-- Sessao.status.
--
-- Tudo que escreve dinheiro roda em funcao SQL (uma transacao). As funcoes
-- sao SECURITY INVOKER: a RLS vale e, como a policy de select deixa admin
-- ver linhas de outros, cada funcao confere owner = auth.uid() explicitamente.
-- Toda mensagem de erro comeca com 'COBRANCA: ' (o app identifica por esse
-- prefixo).

create table "Cobranca" (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  owner uuid not null default auth.uid(),
  paciente bigint not null references "Paciente"(id),
  responsavel_financeiro bigint not null references "ResponsavelFinanceiro"(id),
  -- Primeiro dia do mes de referencia; nulo quando criada pela aba do paciente.
  periodo_referencia date,
  valor_total numeric not null check (valor_total > 0),
  tipo_documento text not null check (tipo_documento in ('nenhum', 'recibo', 'nota_fiscal')),
  situacao text not null default 'aberta' check (situacao in ('aberta', 'recebida', 'cancelada')),
  -- Se o Recebimento for excluido, a cobranca e reaberta por trigger (migration posterior).
  recebimento bigint references "Recebimento"(id) on delete set null,
  recebida_em timestamptz,
  check (situacao <> 'recebida' or recebimento is not null)
);

create table "CobrancaSessao" (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  cobranca bigint not null references "Cobranca"(id),
  -- on delete cascade: o trigger de bloqueio (migration posterior) impede excluir
  -- sessao em cobranca ABERTA, entao o cascade so remove vinculos historicos/inativos.
  sessao bigint not null references "Sessao"(id) on delete cascade,
  -- Valor congelado: saldo devedor da sessao no momento da criacao.
  valor numeric not null check (valor > 0),
  ativa boolean not null default true,
  owner uuid not null default auth.uid()
);

-- Uma sessao so pode estar em uma cobranca ativa (protege duplo clique / duas abas).
create unique index "CobrancaSessao_sessao_ativa_uniq" on "CobrancaSessao" (sessao) where ativa;
create index "CobrancaSessao_cobranca_idx" on "CobrancaSessao" (cobranca);
create index "Cobranca_owner_paciente_idx" on "Cobranca" (owner, paciente);
create index "Cobranca_recebimento_idx" on "Cobranca" (recebimento) where recebimento is not null;

alter table "Cobranca" enable row level security;
alter table "CobrancaSessao" enable row level security;

create policy "cobranca_select_own" on "Cobranca"
  for select using (owner = auth.uid() or public.is_admin());
-- WITH CHECK confere tambem que paciente/responsavel/recebimento referenciados
-- sao do proprio usuario (a checagem de FK ignora RLS). Os subselects rodam com
-- a RLS do chamador, que enxerga as proprias linhas.
create policy "cobranca_insert_own" on "Cobranca"
  for insert with check (
    owner = auth.uid()
    and exists (select 1 from "Paciente" p where p.id = "Cobranca".paciente and p.owner = auth.uid())
    and exists (select 1 from "ResponsavelFinanceiro" r where r.id = "Cobranca".responsavel_financeiro and r.owner = auth.uid())
    and ("Cobranca".recebimento is null
         or exists (select 1 from "Recebimento" rc where rc.id = "Cobranca".recebimento and rc.owner = auth.uid()))
  );
create policy "cobranca_update_own" on "Cobranca"
  for update using (owner = auth.uid() or public.is_admin())
  with check (
    public.is_admin()
    or (
      owner = auth.uid()
      and exists (select 1 from "Paciente" p where p.id = "Cobranca".paciente and p.owner = auth.uid())
      and exists (select 1 from "ResponsavelFinanceiro" r where r.id = "Cobranca".responsavel_financeiro and r.owner = auth.uid())
      and ("Cobranca".recebimento is null
           or exists (select 1 from "Recebimento" rc where rc.id = "Cobranca".recebimento and rc.owner = auth.uid()))
    )
  );
create policy "cobranca_delete_own" on "Cobranca"
  for delete using (owner = auth.uid() or public.is_admin());

create policy "cobrancasessao_select_own" on "CobrancaSessao"
  for select using (owner = auth.uid() or public.is_admin());
-- WITH CHECK: a cobranca e a sessao referenciadas tem que ser do proprio usuario
-- (impede vincular sessao de outro dono e, com isso, bloquear/enumerar a dele).
create policy "cobrancasessao_insert_own" on "CobrancaSessao"
  for insert with check (
    owner = auth.uid()
    and exists (select 1 from "Cobranca" c where c.id = "CobrancaSessao".cobranca and c.owner = auth.uid())
    and exists (select 1 from "Sessao" s where s.id = "CobrancaSessao".sessao and s.owner = auth.uid())
  );
create policy "cobrancasessao_update_own" on "CobrancaSessao"
  for update using (owner = auth.uid() or public.is_admin())
  with check (
    public.is_admin()
    or (
      owner = auth.uid()
      and exists (select 1 from "Cobranca" c where c.id = "CobrancaSessao".cobranca and c.owner = auth.uid())
      and exists (select 1 from "Sessao" s where s.id = "CobrancaSessao".sessao and s.owner = auth.uid())
    )
  );
create policy "cobrancasessao_delete_own" on "CobrancaSessao"
  for delete using (owner = auth.uid() or public.is_admin());

-- ============================================================
-- criar_cobranca: agrupa sessoes elegiveis de um paciente.
-- ============================================================
create or replace function public.criar_cobranca(
  p_paciente bigint,
  p_sessoes bigint[],
  p_tipo_documento text,
  p_periodo date,
  p_responsavel bigint
)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_owner uuid := auth.uid();
  v_ids bigint[];
  v_qtd_pedida int;
  v_qtd_travada int;
  v_total numeric;
  v_cobranca bigint;
  v_invalidas int;
begin
  if v_owner is null then
    raise exception 'COBRANCA: usuário não autenticado.';
  end if;

  if p_tipo_documento is null or p_tipo_documento not in ('nenhum', 'recibo', 'nota_fiscal') then
    raise exception 'COBRANCA: tipo de documento inválido.';
  end if;

  select coalesce(array_agg(distinct x), '{}') into v_ids
    from unnest(p_sessoes) as x
    where x is not null;
  v_qtd_pedida := coalesce(array_length(v_ids, 1), 0);

  if v_qtd_pedida = 0 then
    raise exception 'COBRANCA: selecione ao menos uma sessão.';
  end if;

  if not exists (
    select 1 from "Paciente" where id = p_paciente and owner = v_owner
  ) then
    raise exception 'COBRANCA: paciente não encontrado.';
  end if;

  if p_responsavel is null or not exists (
    select 1 from "ResponsavelFinanceiro" where id = p_responsavel and owner = v_owner
  ) then
    raise exception 'COBRANCA: responsável financeiro não encontrado.';
  end if;

  -- Trava as sessoes (ordem por id evita deadlock entre duas criacoes).
  -- Fica de fora qualquer sessao de outro dono ou de outro paciente.
  perform 1
    from "Sessao"
    where id = any(v_ids) and owner = v_owner and paciente = p_paciente
    order by id
    for update;
  get diagnostics v_qtd_travada = row_count;

  if v_qtd_travada <> v_qtd_pedida then
    raise exception 'COBRANCA: alguma sessão selecionada não foi encontrada para este paciente.';
  end if;

  -- Elegibilidade recalculada no servidor: nao cancelada, sem vinculo ativo, saldo > 0.
  select count(*) into v_invalidas
    from "Sessao" s
    where s.id = any(v_ids)
      and (
        lower(s.status) = 'cancelada'
        or exists (select 1 from "CobrancaSessao" cs where cs.sessao = s.id and cs.ativa)
        or coalesce(s.valor, 0) - coalesce(
          (select sum(rs.valor_aplicado) from "RecebimentoSessao" rs where rs.sessao = s.id), 0
        ) <= 0
      );

  if v_invalidas > 0 then
    raise exception 'COBRANCA: % sessão(ões) selecionada(s) não pode(m) ser cobrada(s): já está em outra cobrança, foi cancelada ou não tem saldo a receber.', v_invalidas;
  end if;

  select sum(
           s.valor - coalesce(
             (select sum(rs.valor_aplicado) from "RecebimentoSessao" rs where rs.sessao = s.id), 0
           )
         )
    into v_total
    from "Sessao" s
    where s.id = any(v_ids);

  begin
    insert into "Cobranca" (owner, paciente, responsavel_financeiro, periodo_referencia, valor_total, tipo_documento)
    values (v_owner, p_paciente, p_responsavel, p_periodo, v_total, p_tipo_documento)
    returning id into v_cobranca;

    insert into "CobrancaSessao" (cobranca, sessao, valor, owner)
    select v_cobranca,
           s.id,
           s.valor - coalesce(
             (select sum(rs.valor_aplicado) from "RecebimentoSessao" rs where rs.sessao = s.id), 0
           ),
           v_owner
      from "Sessao" s
      where s.id = any(v_ids);
  exception when unique_violation then
    raise exception 'COBRANCA: alguma sessão selecionada já entrou em outra cobrança. Atualize a tela e tente de novo.';
  end;

  return v_cobranca;
end;
$$;

-- ============================================================
-- receber_cobranca: recebe a cobranca inteira (uma transacao).
-- Retorna o id do Recebimento criado.
-- ============================================================
create or replace function public.receber_cobranca(
  p_cobranca bigint,
  p_data date,
  p_conta bigint,
  p_forma text
)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_owner uuid := auth.uid();
  v_cob "Cobranca"%rowtype;
  v_lancamento bigint;
  v_recebimento bigint;
  v_conflitos int;
  v_total numeric;
begin
  if v_owner is null then
    raise exception 'COBRANCA: usuário não autenticado.';
  end if;

  if p_data is null then
    raise exception 'COBRANCA: informe a data do recebimento.';
  end if;

  if p_forma is null or p_forma not in ('Dinheiro', 'Pix', 'Cartão') then
    raise exception 'COBRANCA: forma de pagamento inválida.';
  end if;

  -- Trava a linha: duplo clique / duas abas esperam e a segunda ve situacao <> 'aberta'.
  select * into v_cob
    from "Cobranca"
    where id = p_cobranca and owner = v_owner
    for update;

  if not found then
    raise exception 'COBRANCA: cobrança não encontrada.';
  end if;

  if v_cob.situacao <> 'aberta' then
    raise exception 'COBRANCA: esta cobrança não está aberta (situação: %).', v_cob.situacao;
  end if;

  if not exists (
    select 1 from "ContaFinanceira" where id = p_conta and owner = v_owner
  ) then
    raise exception 'COBRANCA: conta financeira não encontrada.';
  end if;

  if not exists (
    select 1 from "CobrancaSessao" where cobranca = v_cob.id and ativa
  ) then
    raise exception 'COBRANCA: a cobrança não tem sessões ativas.';
  end if;

  -- Trava as sessoes e confere que nenhuma ganhou pagamento depois da criacao
  -- (valor congelado + ja aplicado nao pode passar do valor da sessao).
  perform 1
    from "Sessao" s
    join "CobrancaSessao" cs on cs.sessao = s.id and cs.cobranca = v_cob.id and cs.ativa
    order by s.id
    for update of s;

  select count(*) into v_conflitos
    from "CobrancaSessao" cs
    join "Sessao" s on s.id = cs.sessao
    where cs.cobranca = v_cob.id
      and cs.ativa
      and (
        lower(s.status) = 'cancelada'
        or cs.valor + coalesce(
             (select sum(rs.valor_aplicado) from "RecebimentoSessao" rs where rs.sessao = s.id), 0
           ) > coalesce(s.valor, 0)
      );

  if v_conflitos > 0 then
    raise exception 'COBRANCA: % sessão(ões) da cobrança mudou(aram) (cancelada ou já recebida). Cancele esta cobrança e crie outra.', v_conflitos;
  end if;

  -- Total = soma dos valores congelados por sessao (fonte do que sera aplicado).
  select sum(valor) into v_total
    from "CobrancaSessao" where cobranca = v_cob.id and ativa;

  insert into "LancamentoFinanceiro" (data, descricao, valor, tipo, conta, sessao, owner)
  values (p_data, 'Recebimento de cobrança #' || v_cob.id, v_total, 'Receita', p_conta, null, v_owner)
  returning id into v_lancamento;

  insert into "Recebimento" (
    paciente, responsavel_financeiro, data_recebimento, valor_total,
    forma_pagamento, conta, lancamento, owner
  )
  values (
    v_cob.paciente, v_cob.responsavel_financeiro, p_data, v_total,
    p_forma, p_conta, v_lancamento, v_owner
  )
  returning id into v_recebimento;

  -- Sinaliza ao trigger de bloqueio (migration posterior) que este e o caminho
  -- autorizado de recebimento de sessao em cobranca aberta. Vale so nesta transacao.
  perform set_config('app.cobranca_recebendo', 'on', true);

  insert into "RecebimentoSessao" (recebimento, sessao, valor_aplicado, owner)
  select v_recebimento, cs.sessao, cs.valor, v_owner
    from "CobrancaSessao" cs
    where cs.cobranca = v_cob.id and cs.ativa;

  perform set_config('app.cobranca_recebendo', '', true);

  update "Cobranca"
    set situacao = 'recebida',
        recebimento = v_recebimento,
        recebida_em = now()
    where id = v_cob.id;

  return v_recebimento;
end;
$$;

-- ============================================================
-- cancelar_cobranca: so cobranca 'aberta'; libera as sessoes.
-- ============================================================
create or replace function public.cancelar_cobranca(p_cobranca bigint)
returns void
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_owner uuid := auth.uid();
  v_situacao text;
begin
  if v_owner is null then
    raise exception 'COBRANCA: usuário não autenticado.';
  end if;

  select situacao into v_situacao
    from "Cobranca"
    where id = p_cobranca and owner = v_owner
    for update;

  if not found then
    raise exception 'COBRANCA: cobrança não encontrada.';
  end if;

  if v_situacao <> 'aberta' then
    raise exception 'COBRANCA: só é possível cancelar cobrança aberta (situação atual: %).', v_situacao;
  end if;

  update "CobrancaSessao" set ativa = false where cobranca = p_cobranca and ativa;
  update "Cobranca" set situacao = 'cancelada' where id = p_cobranca;
end;
$$;

revoke all on function public.criar_cobranca(bigint, bigint[], text, date, bigint) from public, anon;
revoke all on function public.receber_cobranca(bigint, date, bigint, text) from public, anon;
revoke all on function public.cancelar_cobranca(bigint) from public, anon;
grant execute on function public.criar_cobranca(bigint, bigint[], text, date, bigint) to authenticated;
grant execute on function public.receber_cobranca(bigint, date, bigint, text) to authenticated;
grant execute on function public.cancelar_cobranca(bigint) to authenticated;
